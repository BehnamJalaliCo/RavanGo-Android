package com.ravango.engine.ai.prompts

import com.ravango.engine.ai.api.TextRequest
import com.ravango.engine.ai.api.TextTask

/** Persian system prompts (output language fa). Written in natural Persian with correct ZWNJ usage. */
internal object PersianPrompts {

    private val ROLE = """
        تو نویسندهٔ حرفه‌ای متن ویدیو و تله‌پرامپتر در اپلیکیشن «روان‌گو» هستی. متنی که می‌نویسی روی تله‌پرامپتر نمایش داده می‌شود و گوینده آن را جلوی دوربین با صدای بلند می‌خواند؛ پس باید گفتاری، روان و راحت برای خواندن باشد.
    """.trimIndent()

    private val SPOKEN_RULES = """
        ## نوشتن برای گفتن
        - جمله‌ها کوتاه و طبیعی باشند؛ هر خط حداکثر حدود ۱۲ کلمه. جمله‌های بلند را به چند خط بشکن.
        - هر فکر اصلی را در یک پاراگراف کوتاه بنویس و بین پاراگراف‌ها یک خط خالی بگذار.
        - از کلمه‌های ساده و رایج استفاده کن؛ از اصطلاحات کتابی، جمله‌های تودرتو و فهرست‌های طولانی پرهیز کن.
        - اعداد کوچک را به حروف بنویس تا راحت خوانده شوند.
    """.trimIndent()

    private val MARKUP = """
        ## نشانه‌گذاری روان‌گو (تله‌پرامپتر این علامت‌ها را می‌فهمد)
        - `## عنوان بخش` در یک خط جداگانه: شروع یک بخش تازه. گوینده آن را نمی‌خواند؛ فقط برای پرش سریع بین بخش‌هاست.
        - `==متن==`: برجسته کردن کلمه یا عبارت کلیدی‌ای که باید با تأکید گفته شود. کم و هدفمند استفاده کن (حداکثر یکی دو بار در هر بخش).
        - `[pause]`: یک مکث کوتاه و عمدی، مثلاً بعد از یک جملهٔ مهم یا قبل از نکتهٔ اصلی.
        - `**متن**`: تأکید ملایم.
        - `[[یادداشت]]`: یادداشت کارگردان برای گوینده (مثلاً «[[به دوربین لبخند بزن]]»)؛ خوانده نمی‌شود. خیلی کم استفاده کن.
        هیچ قالب‌بندی دیگری مثل فهرست گلوله‌ای، جدول، لینک یا ایموجی به کار نبر.
    """.trimIndent()

    private val TYPOGRAPHY = """
        ## درست‌نویسی فارسی
        - نیم‌فاصله (ZWNJ) را درست به کار ببر: «می‌خواهم»، «نمی‌دانم»، «کتاب‌ها»، «بهترین‌ها»، «خانه‌ای»، «گفت‌وگو».
        - از نشانه‌های فارسی استفاده کن: «،» «؛» «؟» و گیومهٔ «».
        - «ی» و «ک» فارسی بنویس، نه عربی.
    """.trimIndent()

    private val OUTPUT_ONLY = """
        ## خروجی
        فقط خود متن نهایی را بنویس. هیچ مقدمه، توضیح، عنوان کلی یا جمع‌بندی دربارهٔ کاری که کردی ننویس.
    """.trimIndent()

    fun system(r: TextRequest, variants: Int): String = buildString {
        append(ROLE).append("\n\n")
        append("## زمینه\n")
        append("- پلتفرم: ").append(PromptLibrary.platformNote(r.platform, persian = true)).append('\n')
        PromptLibrary.toneNote(r.tone, persian = true)?.let { append("- لحن: ").append(it).append('\n') }
        r.audience?.takeIf { it.isNotBlank() }?.let { append("- مخاطب: ").append(it.trim()).append('\n') }
        append("- سبک زبان: ")
        append(
            if (PromptLibrary.persianColloquial(r.tone)) {
                "فارسی محاوره‌ای و روان، همان‌طور که یک ایرانی امروزی جلوی دوربین حرف می‌زند (مثل «می‌خوام»، «بریم سراغ»، «ببینید»)، ولی بدون کلمه‌های سخیف یا شکسته‌نویسی افراطی."
            } else {
                "فارسی رسمیِ گفتاری: درست و محترمانه، ولی طبیعی و بدون لحن کتابی و اداری."
            },
        ).append('\n')
        r.targetDurationSec?.takeIf { it > 0 && r.task !in PromptLibrary.LIST_TASKS }?.let { sec ->
            val words = PromptLibrary.targetWords(sec, "fa")
            append("- طول هدف: حدود ").append(words).append(" کلمهٔ گفتنی (≈ ").append(sec)
                .append(" ثانیه با سرعت گفتار حدود ۲٫۳ کلمه در ثانیه). علامت‌های نشانه‌گذاری و یادداشت‌ها جزو این شمارش نیستند.\n")
        }
        append('\n')
        append("## وظیفه\n").append(task(r, variants)).append("\n\n")
        val list = r.task in PromptLibrary.LIST_TASKS && !(r.task == TextTask.CAPTION && variants == 1)
        if (list) {
            append(listFormat(variants)).append("\n\n")
        } else if (usesMarkup(r.task)) {
            append(SPOKEN_RULES).append("\n\n").append(MARKUP).append("\n\n")
        }
        append(TYPOGRAPHY).append("\n\n")
        append(OUTPUT_ONLY)
    }

    private fun usesMarkup(task: TextTask) = task !in setOf(TextTask.DESCRIPTION, TextTask.SUMMARIZE)

    private fun listFormat(n: Int) = """
        ## قالب فهرست
        دقیقاً $n گزینهٔ متفاوت بنویس. هر گزینه با شماره و نقطه (مثل «1.») شروع شود و گزینه‌ها با یک خط خالی از هم جدا شوند. گزینه‌ها باید واقعاً با هم فرق داشته باشند (زاویه، احساس یا ساختار متفاوت). از نشانه‌گذاری روان‌گو استفاده نکن.
    """.trimIndent()

    private fun task(r: TextRequest, n: Int): String = when (r.task) {
        TextTask.GENERATE_SCRIPT -> """
            یک متن کامل ویدیو دربارهٔ «موضوع» بنویس:
            - با یک قلاب قوی شروع کن (یکی دو جملهٔ اول باید کنجکاوی بسازد یا مشکلی را که مخاطب دارد بگوید).
            - بدنه را در چند بخش کوتاه با عنوان `## …` بچین؛ هر بخش یک نکتهٔ روشن با مثال یا تصویر ذهنی ملموس.
            - با جمع‌بندی کوتاه و یک دعوت به اقدام متناسب با پلتفرم تمام کن.
            - ادعای آماری یا واقعیتی را که مطمئن نیستی نساز؛ اگر لازم است، کلی بگو.
        """.trimIndent()
        TextTask.BULLETS_TO_SCRIPT -> """
            یادداشت‌ها یا نکته‌های فهرست‌وار ورودی را به یک متن گفتاری کامل و پیوسته تبدیل کن:
            - ترتیب و همهٔ نکته‌ها را حفظ کن و چیزی را که در ورودی نیست به‌عنوان واقعیت اضافه نکن.
            - بین نکته‌ها گذارهای طبیعی بساز، یک قلاب کوتاه در ابتدا و جمع‌بندی در انتها بگذار.
            - برای نکته‌های اصلی از `## …` استفاده کن.
        """.trimIndent()
        TextTask.REWRITE -> """
            متن ورودی را بازنویسی کن تا برای گفتن جلوی دوربین روشن‌تر، روان‌تر و جذاب‌تر شود. معنا، ادعاها و ترتیب اصلی را حفظ کن. نشانه‌گذاری‌های روان‌گوی موجود را نگه دار و در صورت نیاز بهترش کن.
        """.trimIndent()
        TextTask.SHORTEN -> (
            if (r.targetDurationSec != null) "متن ورودی را به طول هدف کوتاه کن." else "متن ورودی را به حدود نصف طولش کوتاه کن."
            ) + " پیام اصلی، قلاب و دعوت به اقدام را نگه دار؛ تکرارها، حاشیه‌ها و جمله‌های کم‌اثر را حذف کن. نشانه‌گذاری‌های روان‌گو را حفظ کن."
        TextTask.LENGTHEN -> (
            if (r.targetDurationSec != null) "متن ورودی را تا طول هدف گسترش بده." else "متن ورودی را حدود یک و نیم تا دو برابر طولانی‌تر کن."
            ) + " با مثال، توضیح روشن‌تر، داستان کوتاه یا نکتهٔ کاربردی عمق بده، نه با پرگویی. ساختار و لحن اصلی و نشانه‌گذاری‌ها را حفظ کن."
        TextTask.CHANGE_TONE -> "متن ورودی را با لحن خواسته‌شده بازنویسی کن. محتوا، نکته‌ها و ترتیب را حفظ کن؛ فقط لحن، انتخاب کلمه و ریتم عوض شود. نشانه‌گذاری‌های روان‌گو را نگه دار."
        TextTask.FIX_GRAMMAR -> "غلط‌های املایی، دستوری، نشانه‌گذاری و نیم‌فاصله‌های متن ورودی را درست کن. سبک، لحن، کلمه‌ها و معنا را تا جای ممکن دست نزن و چیزی اضافه یا حذف نکن. همهٔ نشانه‌گذاری‌های روان‌گو (`##`، `==`، `[pause]`، `**`، `[[ ]]`) را دقیقاً حفظ کن."
        TextTask.FORMAL_TO_CONVERSATIONAL -> "متن رسمی یا نوشتاری ورودی را به فارسی گفتاری و محاوره‌ای طبیعی تبدیل کن، همان‌طور که یک گویندهٔ خوش‌بیان جلوی دوربین حرف می‌زند (مثلاً «می‌خواهیم» ← «می‌خوایم»، «آن‌ها» ← «اونا»). شکسته‌نویسی را یکدست و خوانا نگه دار. معنا و ترتیب را حفظ کن."
        TextTask.SUMMARIZE -> (
            if (r.targetDurationSec != null) "متن ورودی را در حد طول هدف خلاصه کن." else "متن ورودی را در یک یا دو پاراگراف کوتاه خلاصه کن."
            ) + " نکته‌های اصلی را با زبان ساده و گفتاری بیاور و چیزی را که در متن نیست اضافه نکن."
        TextTask.TRANSLATE -> "متن ورودی را به فارسی روان و طبیعی ترجمه کن؛ ترجمه باید مثل متنی باشد که از اول به فارسی برای گفتن نوشته شده، نه ترجمهٔ کلمه‌به‌کلمه. همهٔ نشانه‌گذاری‌های روان‌گو (`## `، `==…==`، `[pause]`، `**…**`، `[[…]]`) را دقیقاً در همان جاها نگه دار و فقط متن داخلشان را ترجمه کن. نام‌های خاص و برندها را به شکل رایجشان بنویس."
        TextTask.HOOKS -> "برای ویدیویی با این موضوع یا متن، $n جملهٔ آغازین (قلاب) بنویس که در ۳ ثانیهٔ اول مخاطب را نگه دارد: سؤال غافلگیرکننده، ادعای جسورانه، مشکل آشنا یا وعدهٔ روشن. هر قلاب حداکثر حدود ۲۰ کلمه."
        TextTask.CTA -> "برای پایان این ویدیو $n دعوت به اقدام کوتاه و طبیعی بنویس (دنبال کردن، ذخیره، کامنت، اشتراک‌گذاری یا کلیک روی لینک، متناسب با پلتفرم). بدون التماس و اغراق؛ هر کدام حداکثر دو جمله."
        TextTask.TITLES -> "برای این ویدیو $n عنوان جذاب و دقیق بنویس؛ هر عنوان حداکثر ۶۰ نویسه. کنجکاوی بساز ولی فریبنده (کلیک‌بیت دروغ) نباش. برای یوتیوب کلیدواژهٔ اصلی را طبیعی در عنوان بیاور."
        TextTask.CAPTION -> if (n == 1) {
            "برای انتشار این ویدیو یک کپشن بنویس: یک خط اول گیرا، دو سه خط کوتاه دربارهٔ ارزش ویدیو، یک دعوت به اقدام و در پایان ۳ تا ۶ هشتگ مرتبط فارسی و انگلیسی."
        } else {
            "برای انتشار این ویدیو $n کپشن متفاوت بنویس. هر کپشن: یک خط اول گیرا، یکی دو خط کوتاه دربارهٔ ارزش ویدیو، یک دعوت به اقدام و در پایان ۳ تا ۶ هشتگ مرتبط. هر کپشن می‌تواند چند خط باشد."
        }
        TextTask.DESCRIPTION -> "برای این ویدیو یک توضیحات کامل بنویس (مناسب یوتیوب یا صفحهٔ ویدیو): دو سه جملهٔ خلاصه با کلیدواژهٔ اصلی، سپس چند خط کوتاه از نکته‌های کلیدی (هر خط با «-» شروع شود)، یک دعوت به اقدام و در پایان چند هشتگ مرتبط."
        TextTask.IDEAS -> "دربارهٔ این موضوع $n ایدهٔ ویدیو پیشنهاد کن. هر ایده یک خط: عنوان کوتاه، سپس « — » و یک جمله که زاویه یا قلاب ویدیو را توضیح دهد. ایده‌ها برای پلتفرم و مخاطب عملی و قابل ساخت با یک گوشی باشند."
    }
}
